VERIFY_TASK = """\
【本阶段任务：独立事实核验】
你是独立的审核员，不是作者。逐项检查稿件中的每一个产品事实陈述（参数、功能、配置、适用条件、对比性表述），
对照给定的事实点原文与资料，判断：
- supported：资料明确支持，且限定条件没有丢失；
- unsupported：资料里找不到依据；
- conflict：与资料矛盾，或套用了其他型号/款式的事实；
- weakened：资料有依据但丢失了限定条件(如把“典型值”写成了确定值)。
同时检查：稿件是否把相近型号的事实混用；配图说明是否越过了索引描述去推断参数。
只输出 JSON：
{
  "claims": [{"text": "稿件中的原句", "status": "supported|unsupported|conflict|weakened", "evidence": "对应的资料依据或缺失说明", "fix": "建议的改法(删除/改写成…)"}],
  "model_mixup": ["如发现型号混用，写明具体句子"],
  "image_issues": ["配图说明的问题"],
  "pass": true或false
}
对每一个事实性陈述都要有一行 claims；宁严勿松。
但只核验“可被资料证实或证伪的陈述”：问句、号召语、场景描述、读者提问不属于事实陈述，不要列入 claims。
"""

